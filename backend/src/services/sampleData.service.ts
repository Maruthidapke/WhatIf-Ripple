export function getSampleSimulation(input: DecisionInput): SimulationResult {
  const isInternship = input.title.toLowerCase().includes('intern') || input.title.toLowerCase().includes('skill');
  const isBusiness = input.title.toLowerCase().includes('business') || input.title.toLowerCase().includes('20,000') || input.title.toLowerCase().includes('startup');
  const isJobVsEdu = input.title.toLowerCase().includes('education') || input.title.toLowerCase().includes('degree') || input.title.toLowerCase().includes('job');
  const isRelocate = input.title.toLowerCase().includes('city') || input.title.toLowerCase().includes('move') || input.title.toLowerCase().includes('relocat');

  if (isBusiness) {
    return buildBusinessSample(input);
  } else if (isJobVsEdu) {
    return buildEducationVsJobSample(input);
  } else if (isRelocate) {
    return buildRelocationSample(input);
  } else {
    return buildInternshipSample(input);
  }
}

